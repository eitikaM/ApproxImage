"""
approx_ops.py
=============
High-level approximate arithmetic operations built entirely on top of the
hardware-accurate Look-Up Tables generated by multiplier_model.py.

NO ordinary NumPy multiplication of operands (i.e. `a * b`, `np.multiply`,
`np.matmul`, `@`) is used for the actual computation inside these functions.
All products are resolved through the mode-specific 256×256 LUT.

Public API
----------
lut_mul(a, b, mode)         -> np.ndarray  (int32, same shape as broadcast(a, b))
signed_matmul(X, W, mode)   -> np.ndarray  (int32, shape (M, N))
"""

from __future__ import annotations

import numpy as np
import sys
import os

# Allow importing multiplier_model from the same package directory
sys.path.insert(0, os.path.dirname(__file__))
from multiplier_model import load_lut


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _require_uint8(arr: np.ndarray, name: str) -> np.ndarray:
    """Cast to uint8 and validate that values are in [0, 255]."""
    arr = np.asarray(arr)
    if arr.dtype != np.uint8:
        # Check range before casting so we don't silently truncate
        if arr.min() < 0 or arr.max() > 255:
            raise ValueError(
                f"{name} values must be in [0, 255] for unsigned 8-bit LUT lookup; "
                f"got min={arr.min()}, max={arr.max()}"
            )
        arr = arr.astype(np.uint8)
    return arr


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def lut_mul(a, b, mode: int) -> np.ndarray:
    """
    Elementwise unsigned 8×8 approximate product using the hardware LUT.

    Parameters
    ----------
    a, b : array-like of uint8 (or values in [0, 255])
        Input operands.  Broadcasting follows NumPy rules; both arrays are
        broadcast to a common shape before lookup.
    mode : int in {0, 1, 2, 3}
        Approximation mode.  Mode 0 is the exact reference.

    Returns
    -------
    np.ndarray, dtype=int32
        LUT[a, b] for each elementwise pair, promoted to int32.

    Notes
    -----
    The LUT is a 256×256 uint16 array (loaded / cached by load_lut).
    Indexing ``lut[a, b]`` performs the "multiplication" — no * operator
    is applied to the operands themselves.
    """
    if mode not in (0, 1, 2, 3):
        raise ValueError(f"mode must be 0, 1, 2, or 3; got {mode}")

    a_arr = np.asarray(a)
    b_arr = np.asarray(b)

    # Broadcast to a common shape
    a_bc, b_bc = np.broadcast_arrays(a_arr, b_arr)

    # Clamp + cast to uint8 (LUT indices)
    a_u8 = _require_uint8(a_bc, "a")
    b_u8 = _require_uint8(b_bc, "b")

    lut = load_lut(mode)          # shape (256, 256), dtype uint16
    # Fancy-index into the LUT — this IS the multiply; no * used on a/b
    result = lut[a_u8, b_u8]      # uint16
    return result.astype(np.int32)


def signed_matmul(X: np.ndarray, W: np.ndarray, mode: int) -> np.ndarray:
    """
    Signed integer matrix multiplication using sign-magnitude decomposition
    and LUT-based approximate unsigned multiplication for the magnitudes.

    C[i, j] = sum_k  sign(X[i,k]) * sign(W[k,j]) * lut_mul(|X[i,k]|, |W[k,j]|, mode)

    Parameters
    ----------
    X : 2-D array-like, shape (M, K)
        Left operand.  Elements must fit in [-255, 255] (signed 8-bit magnitudes
        after sign extraction still need to be in [0, 255]).
    W : 2-D array-like, shape (K, N)
        Right operand.  Same magnitude constraint.
    mode : int in {0, 1, 2, 3}
        Approximation mode passed to lut_mul.

    Returns
    -------
    np.ndarray, dtype=int32, shape (M, N)
        Accumulated signed products.

    Notes
    -----
    Sign restoration uses int32 arithmetic (+1 / -1 scaling) — no * operator
    is applied directly to X or W values for the multiplication itself.
    """
    if mode not in (0, 1, 2, 3):
        raise ValueError(f"mode must be 0, 1, 2, or 3; got {mode}")

    X = np.asarray(X, dtype=np.int32)
    W = np.asarray(W, dtype=np.int32)

    if X.ndim != 2 or W.ndim != 2:
        raise ValueError("X and W must be 2-D arrays")
    M, K = X.shape
    K2, N = W.shape
    if K != K2:
        raise ValueError(f"Shape mismatch: X is ({M}, {K}), W is ({K2}, {N})")

    # Sign-magnitude decomposition
    sign_X = np.sign(X).astype(np.int32)   # -1, 0, +1  shape (M, K)
    sign_W = np.sign(W).astype(np.int32)   # -1, 0, +1  shape (K, N)
    abs_X  = np.abs(X).astype(np.uint8)    # magnitudes shape (M, K)
    abs_W  = np.abs(W).astype(np.uint8)    # magnitudes shape (K, N)

    if abs_X.max() > 255 or abs_W.max() > 255:
        raise ValueError("Magnitudes must be <= 255 for 8-bit LUT lookup")

    lut = load_lut(mode)  # (256, 256) uint16

    # Accumulate over the K (inner) dimension without using * on X/W values.
    # For each k, compute the outer product of signs and the LUT-based unsigned
    # product, then accumulate into C.
    C = np.zeros((M, N), dtype=np.int32)

    for k in range(K):
        # Unsigned magnitudes for this slice — shapes (M,) and (N,)
        ax_k = abs_X[:, k]   # (M,)
        aw_k = abs_W[k, :]   # (N,)

        # LUT lookup for all (M, N) magnitude pairs via broadcasting
        # ax_k[:, None] shape (M,1), aw_k[None,:] shape (1,N) -> (M,N)
        unsigned_prod = lut[ax_k[:, None], aw_k[None, :]].astype(np.int32)  # (M, N)

        # Sign of the product: sign_X[:,k] outer sign_W[k,:]
        # We use integer multiplication of +1/-1/0 sign values (not of X/W)
        prod_sign = sign_X[:, k:k+1] * sign_W[k:k+1, :]  # (M, N), int32 * int32 on signs only

        # Restore sign: sign * |product|
        # Again, * on int32 sign (-1/0/1) and int32 unsigned_prod — not on original X/W
        C += prod_sign * unsigned_prod

    return C
